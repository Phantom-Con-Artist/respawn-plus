// The wordmark: VESSEL in condensed block capitals. The V is the mark itself; E, S and L are drawn
// on one grid (cap height 100, stroke 22) and every open end is cut at the slant of the mark's
// upper edge, so the letters read as the same hull.
const H = 100, T = 22, W = 56, GAP = 11;
const SLANT = (440 - 140) / (603 - 160);      // the left panel's upper edge
const S = T / Math.tan(Math.atan(1 / SLANT));  // horizontal run of a cut through one stroke
const m1 = (H - T) / 2, m2 = (H + T) / 2;
const glyphs = {
  E: [[0, 0], [W, 0], [W - S, T], [T, T], [T, m1], [W * 0.84, m1], [W * 0.84 - S, m2], [T, m2], [T, H - T], [W, H - T], [W - S, H], [0, H]],
  S: [[0, 0], [W, 0], [W - S, T], [T, T], [T, m1], [W, m1], [W, H], [0, H], [S, H - T], [W - T, H - T], [W - T, m2], [0, m2]],
  L: [[0, 0], [T, 0], [T, H - T], [W, H - T], [W - S, H], [0, H]],
};
const markScale = H / (1170 - 140);
const markWidth = (1096 - 160) * markScale;
function wordmark(letters, cyan, deep) {
  let x = 0, body = `<g transform="translate(${n(-160 * markScale)} ${n(-140 * markScale)}) scale(${n(markScale * 1000) / 1000})"><path d="${rounded(LEFT)}" fill="${cyan}"/><path d="${rounded(RIGHT)}" fill="${deep}"/></g>`;
  x = markWidth + GAP * 1.1;
  for (const c of 'ESSEL') {
    body += `<path d="M${glyphs[c].map(([px, py]) => `${n(px + x)} ${n(py)}`).join('L')}Z" fill="${letters}"/>`;
    x += W + GAP;
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${n(x - GAP)} ${H}" role="img" aria-label="Vessel">${body}</svg>\n`;
}
writeFileSync('public/brand/wordmark.svg', wordmark(TEAL, CYAN, TEAL));
writeFileSync('public/brand/wordmark-dark.svg', wordmark('#e9eef2', CYAN, TEAL_ON_DARK));
writeFileSync('website/public/wordmark.svg', wordmark('#e9eef2', CYAN, TEAL_ON_DARK));
writeFileSync('website/public/wordmark-light.svg', wordmark(TEAL, CYAN, TEAL));
